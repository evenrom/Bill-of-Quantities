  const insert=page.getByRole('button',{name:'הוספה לפני בנייה ומחיצות פנים, שורה 2',exact:true});
  const cell=page.getByLabel('תיאור בנייה ומחיצות פנים, שורה 2',{exact:true});
  await cell.scrollIntoViewIfNeeded();const box=await cell.locator('xpath=ancestor::tr').boundingBox();
  await page.mouse.move(box!.x+box!.width-16,box!.y+1);
  await expect(insert).toHaveCSS('opacity','1');await insert.click();
  await page.getByRole('button',{name:'סעיף חדש',exact:true}).click();
  await expect(chapter.locator('tr[data-row-id]')).toHaveCount(before+1);
  await expect(cell).toBeFocused();await cell.fill('סעיף שנוסף בין שורות');
  const quantity=page.getByLabel('כמות בנייה ומחיצות פנים, שורה 2',{exact:true});
  await quantity.fill('2');await page.getByLabel('מחיר בנייה ומחיצות פנים, שורה 2',{exact:true}).fill('50');
  const convert=page.getByRole('button',{name:'שינוי סוג בנייה ומחיצות פנים, שורה 2',exact:true});
  await page.getByRole('button',{name:'פעולות בנייה ומחיצות פנים, שורה 2',exact:true}).click();page.once('dialog',d=>d.dismiss());await convert.click();await expect(quantity).toHaveValue('2');
